# Program ini menggunakan fungsi input()
# Program konversi nilai angka menjadi huruf

nilai_2023 = int(input("Masukkan Nilai Angka : "))

if nilai_2023 >= 81:
    print("A")
elif nilai_2023 >= 70:
    print("B")
elif nilai_2023 >= 60:
    print("C")
elif nilai_2023 >= 50:
    print("D")
else:
    print("E")
    